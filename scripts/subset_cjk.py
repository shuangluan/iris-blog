"""Subset Noto Serif SC to woff2. stdin: JSON spec from subset-cjk.mjs."""

import json
import sys
from pathlib import Path

from fontTools.subset import Options, Subsetter
from fontTools.ttLib import TTFont


def subset(src: str, unicodes: list[int], dest: Path) -> None:
    font = TTFont(src)
    opts = Options()
    opts.layout_features = ["kern", "liga", "palt"]
    opts.desubroutinize = True
    opts.hinting = False
    opts.notdef_outline = True
    opts.drop_tables = ["DSIG"]
    sub = Subsetter(options=opts)
    sub.populate(unicodes=unicodes)
    sub.subset(font)
    font.flavor = "woff2"
    dest.parent.mkdir(parents=True, exist_ok=True)
    font.save(str(dest))


def has_feature(path: Path, tag: str) -> bool:
    font = TTFont(str(path))
    for table in ("GSUB", "GPOS"):
        if table not in font:
            continue
        records = font[table].table.FeatureList.FeatureRecord
        if any(r.FeatureTag == tag for r in records):
            return True
    return False


def unicode_range(cps: list[int]) -> str:
    ordered = sorted(set(cps))
    if not ordered:
        return ""
    parts: list[str] = []
    start = prev = ordered[0]
    for cp in ordered[1:]:
        if cp == prev + 1:
            prev = cp
            continue
        parts.append(fmt_range(start, prev))
        start = prev = cp
    parts.append(fmt_range(start, prev))
    return ", ".join(parts)


def fmt_range(start: int, end: int) -> str:
    a = f"U+{start:04X}"
    if start == end:
        return a
    return f"{a}-{end:04X}"


def main() -> None:
    spec = json.load(sys.stdin)
    groups: list[list[int]] = spec["groups"]
    out = Path(spec["outDir"])
    faces: list[str] = [
        "/* Generated by scripts/subset-cjk.mjs. Extra unicode-range chunks.",
        "   Chunk 0 is loaded with next/font/local. Do not edit. */",
        "",
    ]
    sources = {"400": spec["regular"], "600": spec["semibold"]}

    for index, cps in enumerate(groups):
        for weight, src in sources.items():
            if index == 0:
                name = f"NotoSerifSC-subset-{weight}.woff2"
            else:
                name = f"NotoSerifSC-{weight}-{index}.woff2"
            dest = out / name
            subset(src, cps, dest)
            size = dest.stat().st_size
            print(f"{name} {size} bytes  glyphs-requested {len(set(cps))}")
            if index == 0 and weight == "400":
                for tag in ("kern", "palt"):
                    if not has_feature(dest, tag):
                        sys.exit(f"subset is missing required layout feature {tag}")
                if not has_feature(dest, "liga"):
                    print("warning: liga not present in chunk 0 (no ligature glyphs)", file=sys.stderr)
            if index > 0:
                ur = unicode_range(cps)
                faces.append(
                    "\n".join(
                        [
                            "@font-face {",
                            '  font-family: "Noto Serif SC";',
                            f'  src: url("/fonts/{name}") format("woff2");',
                            f"  font-weight: {weight};",
                            "  font-style: normal;",
                            "  font-display: swap;",
                            f"  unicode-range: {ur};",
                            "}",
                            "",
                        ]
                    )
                )

    Path(spec["css"]).write_text("\n".join(faces), encoding="utf-8")


if __name__ == "__main__":
    main()
